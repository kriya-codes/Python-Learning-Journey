# String is a sequence charaters like alphabets, spaces, special charaters(@,#,$...)
str="Hello"
print(str)

# Find the length(count of charaters) of a string len(), a build-in function
print("Length:", len(str))

# To convert a string into uppercase or lowercase in Python, use the built-in upper() and lower() string methods.
print("Uppercase:", str.upper())
print("Lowercase:", str.lower())
